-- PulsePlate Alpha database schema for Supabase/PostgreSQL.
-- Run this in Supabase SQL Editor before using the alpha.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'PulsePlate User',
  email text,
  role text not null default 'user' check (role in ('user','trainer')),
  business_name text,
  primary_goal text not null default 'health' check (primary_goal in ('lose','maintain','gain','health','custom')),
  onboarding_complete boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.nutrition_goals (
  user_id uuid primary key references auth.users(id) on delete cascade,
  calorie_goal integer not null default 2050 check (calorie_goal between 500 and 10000),
  protein_goal numeric not null default 147 check (protein_goal between 0 and 1000),
  carbs_goal numeric not null default 230 check (carbs_goal between 0 and 1500),
  fat_goal numeric not null default 68 check (fat_goal between 0 and 500),
  current_weight numeric,
  goal_weight numeric,
  updated_at timestamptz not null default now()
);

create table if not exists public.food_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  logged_date date not null default current_date,
  meal text not null default 'Meal',
  food_name text not null,
  serving text not null default '1 serving',
  fdc_id bigint,
  calories numeric not null default 0,
  protein numeric not null default 0,
  carbs numeric not null default 0,
  fat numeric not null default 0,
  created_at timestamptz not null default now()
);


